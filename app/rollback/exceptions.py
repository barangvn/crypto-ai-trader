from __future__ import annotations

from typing import Any


ERR_ROLLBACK_INVALID_TRIGGER_TYPE = "INVALID_TRIGGER_TYPE"
ERR_ROLLBACK_INCOMPLETE_EVIDENCE = "INCOMPLETE_EVIDENCE"
ERR_ROLLBACK_DELTA_METRICS_INCOMPLETE = "DELTA_METRICS_INCOMPLETE"
ERR_ROLLBACK_MIN_ROLLBACK_APPROVALS_FAIL = "MIN_ROLLBACK_APPROVALS_FAIL"
ERR_ROLLBACK_STALE_DEGRADATION_WINDOW = "STALE_DEGRADATION_WINDOW"
ERR_ROLLBACK_EVIDENCE_INTEGRITY_MISMATCH = "EVIDENCE_INTEGRITY_MISMATCH"
ERR_ROLLBACK_MISSING_ROLLBACK_TARGET = "MISSING_ROLLBACK_TARGET"
ERR_ROLLBACK_INELIGIBLE_ROLLBACK_TARGET_STATUS = "INELIGIBLE_ROLLBACK_TARGET_STATUS"
ERR_ROLLBACK_ROLLBACK_TARGET_ARTIFACT_CORRUPT = "ROLLBACK_TARGET_ARTIFACT_CORRUPT"
ERR_ROLLBACK_ROLLBACK_STRATEGY_MISSING = "ROLLBACK_STRATEGY_MISSING"
ERR_ROLLBACK_CURRENT_NOT_CHAMPION = "CURRENT_NOT_CHAMPION"
ERR_ROLLBACK_DEGRADATION_EVIDENCE_COUNT_BELOW_MIN = "DEGRADATION_EVIDENCE_COUNT_BELOW_MIN"
ERR_ROLLBACK_APPROVER_IDENTITY_EMPTY = "APPROVER_IDENTITY_EMPTY"
ERR_ROLLBACK_RATIONALE_EMPTY = "RATIONALE_EMPTY"
ERR_ROLLBACK_PRIOR_STATE_REF_NULL = "PRIOR_STATE_REF_NULL"
ERR_ROLLBACK_STRATEGY_REF_ARTIFACT_NOT_FOUND = "STRATEGY_REF_ARTIFACT_NOT_FOUND"
ERR_ROLLBACK_THRESHOLDS_VERSION_MISMATCH = "THRESHOLDS_VERSION_MISMATCH"


ROLLBACK_REASON_CODES: tuple[str, ...] = (
    ERR_ROLLBACK_INVALID_TRIGGER_TYPE,
    ERR_ROLLBACK_INCOMPLETE_EVIDENCE,
    ERR_ROLLBACK_DELTA_METRICS_INCOMPLETE,
    ERR_ROLLBACK_MIN_ROLLBACK_APPROVALS_FAIL,
    ERR_ROLLBACK_STALE_DEGRADATION_WINDOW,
    ERR_ROLLBACK_EVIDENCE_INTEGRITY_MISMATCH,
    ERR_ROLLBACK_MISSING_ROLLBACK_TARGET,
    ERR_ROLLBACK_INELIGIBLE_ROLLBACK_TARGET_STATUS,
    ERR_ROLLBACK_ROLLBACK_TARGET_ARTIFACT_CORRUPT,
    ERR_ROLLBACK_ROLLBACK_STRATEGY_MISSING,
    ERR_ROLLBACK_CURRENT_NOT_CHAMPION,
    ERR_ROLLBACK_DEGRADATION_EVIDENCE_COUNT_BELOW_MIN,
    ERR_ROLLBACK_APPROVER_IDENTITY_EMPTY,
    ERR_ROLLBACK_RATIONALE_EMPTY,
    ERR_ROLLBACK_PRIOR_STATE_REF_NULL,
    ERR_ROLLBACK_STRATEGY_REF_ARTIFACT_NOT_FOUND,
    ERR_ROLLBACK_THRESHOLDS_VERSION_MISMATCH,
)


_VALID_REASON_SET: set[str] = set(ROLLBACK_REASON_CODES)


class RollbackValidationError(Exception):
    reason_code: str
    message: str
    details: dict[str, Any]

    def __init__(
        self,
        reason_code: str,
        message: str,
        details: dict[str, Any] | None = None,
    ) -> None:
        if not isinstance(reason_code, str) or not reason_code:
            raise ValueError("reason_code must be a non-empty str")
        if reason_code not in _VALID_REASON_SET:
            raise ValueError(
                f"reason_code {reason_code!r} not in ROLLBACK_REASON_CODES set"
            )
        if not isinstance(message, str) or not message:
            raise ValueError("message must be a non-empty str")
        self.reason_code = reason_code
        self.message = message
        self.details = dict(details) if details else {}
        super().__init__(f"[{reason_code}] {message}")
